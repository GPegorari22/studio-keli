-- Área pedagógica da professora. Todas as operações verificam a professora
-- autenticada e filtram as turmas atribuídas a ela no banco.

create table if not exists public.professora_evolucao (
  id_evolucao bigint generated by default as identity primary key,
  id_professor integer not null references public.professor(id_professor),
  id_aluno integer not null references public.aluno(id_aluno),
  id_turma integer references public.turma(id_turma),
  avaliacao jsonb not null default '{}'::jsonb,
  observacao text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.professora_feedback (
  id_feedback bigint generated by default as identity primary key,
  id_professor integer not null references public.professor(id_professor),
  id_aluno integer not null references public.aluno(id_aluno),
  id_turma integer references public.turma(id_turma),
  data_feedback date not null default current_date,
  texto text not null,
  visivel_aluno boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.professora_frequencia_detalhe (
  id_frequencia integer primary key references public.frequencia(id_frequencia) on delete cascade,
  justificativa text,
  observacao text,
  atualizado_em timestamptz not null default now()
);

create index if not exists professora_evolucao_aluno_idx on public.professora_evolucao(id_aluno, criado_em desc);
create index if not exists professora_feedback_aluno_idx on public.professora_feedback(id_aluno, data_feedback desc);

create or replace function public.professora_atual()
returns public.professor
language sql stable security definer set search_path = ''
as $$
  select p.*
  from public.professor p
  join public.usuario u on u.id_usuario = p.id_usuario
  join public.perfil pf on pf.id_perfil = u.id_perfil
  where u.id_usuario = auth.uid()
    and lower(trim(coalesce(u.status, 'ativo'))) in ('ativo', 'ativa')
    and lower(trim(pf.nome)) in ('professor', 'professora', 'professores', 'funcionario')
  order by p.id_professor
  limit 1;
$$;

create or replace function public.is_professora()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.professora_atual());
$$;

create or replace function public.painel_professora()
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  prof public.professor;
  resposta jsonb;
begin
  select * into prof from public.professora_atual();
  if prof.id_professor is null then
    raise exception 'Acesso de professora não autorizado.' using errcode = '42501';
  end if;

  select jsonb_build_object(
    'professora', jsonb_build_object('id', prof.id_professor, 'nome', prof.nome, 'email', prof.email, 'telefone', prof.telefone, 'especialidade', prof.especialidade, 'status', prof.status),
    'usuario', (select jsonb_build_object('id', u.id_usuario, 'nome', u.nome, 'email', u.email, 'telefone', u.telefone) from public.usuario u where u.id_usuario = auth.uid()),
    'indicadores', jsonb_build_object(
      'aulas_hoje', (select count(*) from public.aula a join public.turma t on t.id_turma = a.id_turma where t.id_professor = prof.id_professor and a.data_aula = timezone('America/Sao_Paulo', now())::date),
      'alunos', (select count(distinct m.id_aluno) from public.matricula m join public.turma t on t.id_turma = m.id_turma where t.id_professor = prof.id_professor and lower(trim(m.status)) in ('ativo', 'ativa')),
      'turmas', (select count(*) from public.turma t where t.id_professor = prof.id_professor and lower(trim(t.status)) in ('ativo', 'ativa')),
      'pendencias', (select count(*) from public.aula a join public.turma t on t.id_turma = a.id_turma where t.id_professor = prof.id_professor and a.data_aula <= timezone('America/Sao_Paulo', now())::date and not exists (select 1 from public.frequencia f where f.id_aula = a.id_aula))
    ),
    'turmas', coalesce((select jsonb_agg(jsonb_build_object('id', t.id_turma, 'nome', t.nome, 'dia', t.dia_semana, 'horario', t.horario, 'capacidade', t.capacidade, 'status', t.status, 'modalidade', mo.nome, 'alunos', (select count(*) from public.matricula m where m.id_turma = t.id_turma and lower(trim(m.status)) in ('ativo', 'ativa'))) order by t.nome) from public.turma t left join public.modalidade mo on mo.id_modalidade = t.id_modalidade where t.id_professor = prof.id_professor), '[]'::jsonb),
    'agenda', coalesce((select jsonb_agg(jsonb_build_object('id', a.id_aula, 'turma_id', t.id_turma, 'data', a.data_aula, 'inicio', a.horario_inicio, 'fim', a.horario_fim, 'status', a.status, 'turma', t.nome, 'sala', 'A definir') order by a.data_aula, a.horario_inicio) from public.aula a join public.turma t on t.id_turma = a.id_turma where t.id_professor = prof.id_professor and a.data_aula between current_date - 7 and current_date + 45), '[]'::jsonb),
    'alunos', coalesce((select jsonb_agg(jsonb_build_object('id', al.id_aluno, 'nome', al.nome, 'foto', al.foto_perfil, 'turma', t.nome, 'turma_id', t.id_turma, 'frequencia', (select round(100.0 * count(*) filter (where f.presente) / nullif(count(*), 0), 1) from public.frequencia f join public.aula aa on aa.id_aula = f.id_aula where f.id_aluno = al.id_aluno and aa.id_turma = t.id_turma), 'ultima_presenca', (select max(aa.data_aula) from public.frequencia f join public.aula aa on aa.id_aula = f.id_aula where f.id_aluno = al.id_aluno and aa.id_turma = t.id_turma)) order by al.nome) from public.aluno al join public.matricula m on m.id_aluno = al.id_aluno join public.turma t on t.id_turma = m.id_turma where t.id_professor = prof.id_professor and lower(trim(m.status)) in ('ativo', 'ativa')), '[]'::jsonb),
    'avisos', coalesce((select jsonb_agg(jsonb_build_object('id', c.id_comunicado, 'titulo', c.titulo, 'conteudo', c.conteudo, 'data', c.data_envio, 'lido', cu.lido) order by c.data_envio desc) from public.comunicado_usuario cu join public.comunicado c on c.id_comunicado = cu.id_comunicado where cu.id_usuario = auth.uid()), '[]'::jsonb)
  ) into resposta;
  return resposta;
end;
$$;

create or replace function public.professora_registrar_frequencia(
  p_id_aula integer, p_id_aluno integer, p_presente boolean,
  p_justificativa text default null, p_observacao text default null
)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  prof public.professor;
  registro public.frequencia;
begin
  select * into prof from public.professora_atual();
  if prof.id_professor is null then raise exception 'Acesso não autorizado.' using errcode = '42501'; end if;
  if not exists (select 1 from public.aula a join public.turma t on t.id_turma = a.id_turma join public.matricula m on m.id_turma = t.id_turma where a.id_aula = p_id_aula and m.id_aluno = p_id_aluno and t.id_professor = prof.id_professor) then
    raise exception 'A aula ou o aluno não pertence às suas turmas.' using errcode = '42501';
  end if;
  select * into registro from public.frequencia where id_aula = p_id_aula and id_aluno = p_id_aluno order by data_registro desc, id_frequencia desc limit 1;
  if registro.id_frequencia is null then
    insert into public.frequencia (id_aula, id_aluno, presente) values (p_id_aula, p_id_aluno, p_presente) returning * into registro;
  else
    update public.frequencia set presente = p_presente, data_registro = now() where id_frequencia = registro.id_frequencia returning * into registro;
  end if;
  insert into public.professora_frequencia_detalhe (id_frequencia, justificativa, observacao, atualizado_em) values (registro.id_frequencia, nullif(trim(p_justificativa), ''), nullif(trim(p_observacao), ''), now()) on conflict (id_frequencia) do update set justificativa = excluded.justificativa, observacao = excluded.observacao, atualizado_em = now();
  return jsonb_build_object('id', registro.id_frequencia, 'presente', registro.presente);
end;
$$;

create or replace function public.professora_salvar_evolucao(
  p_id_aluno integer, p_id_turma integer, p_avaliacao jsonb, p_observacao text default null
)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare prof public.professor; item_id bigint;
begin
  select * into prof from public.professora_atual();
  if prof.id_professor is null or not exists (select 1 from public.matricula m join public.turma t on t.id_turma = m.id_turma where m.id_aluno = p_id_aluno and t.id_turma = p_id_turma and t.id_professor = prof.id_professor) then raise exception 'Aluno não pertence a uma turma da professora.' using errcode = '42501'; end if;
  insert into public.professora_evolucao (id_professor, id_aluno, id_turma, avaliacao, observacao) values (prof.id_professor, p_id_aluno, p_id_turma, coalesce(p_avaliacao, '{}'::jsonb), nullif(trim(p_observacao), '')) returning id_evolucao into item_id;
  return jsonb_build_object('id', item_id);
end;
$$;

create or replace function public.professora_salvar_feedback(
  p_id_aluno integer, p_id_turma integer, p_texto text, p_visivel_aluno boolean default true, p_data date default current_date
)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare prof public.professor; item_id bigint;
begin
  select * into prof from public.professora_atual();
  if prof.id_professor is null or nullif(trim(p_texto), '') is null or not exists (select 1 from public.matricula m join public.turma t on t.id_turma = m.id_turma where m.id_aluno = p_id_aluno and t.id_turma = p_id_turma and t.id_professor = prof.id_professor) then raise exception 'Informe um feedback válido para um aluno da sua turma.' using errcode = '22023'; end if;
  insert into public.professora_feedback (id_professor, id_aluno, id_turma, texto, visivel_aluno, data_feedback) values (prof.id_professor, p_id_aluno, p_id_turma, trim(p_texto), coalesce(p_visivel_aluno, true), coalesce(p_data, current_date)) returning id_feedback into item_id;
  return jsonb_build_object('id', item_id);
end;
$$;

create or replace function public.professora_marcar_aviso_lido(p_id_comunicado integer)
returns boolean language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_professora() then raise exception 'Acesso não autorizado.' using errcode = '42501'; end if;
  update public.comunicado_usuario set lido = true, data_leitura = now() where id_comunicado = p_id_comunicado and id_usuario = auth.uid();
  return found;
end;
$$;

create or replace function public.professora_marcar_todos_avisos_lidos()
returns integer language plpgsql security definer set search_path = ''
as $$
declare total integer;
begin
  if not public.is_professora() then raise exception 'Acesso não autorizado.' using errcode = '42501'; end if;
  update public.comunicado_usuario set lido = true, data_leitura = now() where id_usuario = auth.uid() and not lido;
  get diagnostics total = row_count;
  return total;
end;
$$;

